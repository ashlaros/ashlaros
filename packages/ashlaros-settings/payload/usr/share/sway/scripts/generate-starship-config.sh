\$conda\\
[](fg:sapphire bg:lavender)\\
\$time\\
[ ](fg:lavender)\\
\$cmd_duration"""

palette = 'ashlaros'


[username]
show_always = true
style_user = "bg:red fg:crust"
style_root = "bg:red fg:crust"
format = '[ \$user](\$style)'

[directory]
