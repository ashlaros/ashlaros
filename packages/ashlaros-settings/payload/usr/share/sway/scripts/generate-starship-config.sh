[git_status]
style = "bg:yellow"
format = '[[(\$all_status\$ahead_behind )](fg:crust bg:yellow)](\$style)'

[nodejs]
symbol = ""
style = "bg:green"
format = '[[ \$symbol( \$version) ](fg:crust bg:green)](\$style)'

[bun]
symbol = ""
style = "bg:green"
format = '[[ \$symbol( \$version) ](fg:crust bg:green)](\$style)'

[c]
symbol = " "
style = "bg:green"
format = '[[ \$symbol( \$version) ](fg:crust bg:green)](\$style)'

[rust]
symbol = ""
style = "bg:green"
format = '[[ \$symbol( \$version) ](fg:crust bg:green)](\$style)'

[golang]
symbol = ""
style = "bg:green"
format = '[[ \$symbol( \$version) ](fg:crust bg:green)](\$style)'

